// Inline drizzle-kit's generated SQL into a TS module Metro can bundle (no .sql imports, no
// babel plugin) and Vitest can import. Run via `pnpm db:generate`.
import { readFileSync, writeFileSync } from 'node:fs'

const dir = new URL('../drizzle/', import.meta.url)
const journal = JSON.parse(readFileSync(new URL('meta/_journal.json', dir), 'utf8'))
const migrations = journal.entries.map((e) => ({
  tag: e.tag,
  sql: readFileSync(new URL(`${e.tag}.sql`, dir), 'utf8'),
}))
const out = `// GENERATED by scripts/bundle-migrations.mjs from drizzle/ — do not edit.

export const MIGRATIONS: readonly { tag: string; sql: string }[] = ${JSON.stringify(migrations, null, 2)}
`
writeFileSync(new URL('../src/data/migrations.gen.ts', import.meta.url), out)
console.log(`bundled ${migrations.length} migration(s)`)
